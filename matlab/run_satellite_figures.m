function run_satellite_figures(export_figures)
% Run the existing satellite-count and skyplot routines only.
% Edit these paths when using another checkout or output directory.
repo_dir = 'F:/RTKLib-LAB';
if nargin < 1, export_figures = false; end
output_dir = fullfile(repo_dir, 'matlab', 'figures', 'satellites');
script_root = fullfile(repo_dir, 'matlab', 'result');
sites = {'JC01','JC02','JC04'};
if ~isfolder(output_dir), mkdir(output_dir); end
previous_visibility = get(groot, 'defaultFigureVisible');
set(groot, 'defaultFigureVisible', 'on');
cleanup = onCleanup(@() set(groot, 'defaultFigureVisible', previous_visibility));
for s = 1:numel(sites)
    site = sites{s};
    source = fileread(fullfile(script_root, site, 'plot_paper.m'));
    % Preserve the original settings and local plotting functions verbatim.
    head_end = strfind(source, 'methods = [');
    local_start = strfind(source, 'function data = read_static_pint');
    assert(~isempty(head_end) && ~isempty(local_start), 'Unexpected script layout');
    header = source(1:head_end(1)-1);
    header = strrep(header, 'close all; clear; clc;', '');
    header = strrep(header, "out_dir = fullfile(script_dir, 'paper_figures');", ...
        sprintf("out_dir = '%s';", strrep(fullfile(output_dir, site), '\', '/')));
    header = [header newline 'cfg.export_png = export_figures; cfg.export_fig = false;' newline];
    body = sprintf([...
        '\nref = fixed_ecef_reference(truth_ecef);\n' ...
        'epochs = read_rinex_observed_satellites(obs_file);\n' ...
        'sat_counts = read_static_rinex_satellite_counts(obs_file, epochs.time);\n' ...
        'skyplot_data = build_skyplot_data(obs_file, nav_file, ref);\n' ...
        'figs_before = findall(groot, ''Type'', ''figure'');\n' ...
        'plot_dual_system_satellite_counts(sat_counts.gps, sat_counts.bds, cfg, fullfile(out_dir, ''fig2_sat_count''));\n' ...
        'plot_skyplot(skyplot_data, cfg, fullfile(out_dir, ''fig3_skyplot''));\n' ...
        'figs = setdiff(findall(groot, ''Type'', ''figure''), figs_before);\n' ...
        'set(figs, ''Visible'', ''on'', ''ToolBar'', ''figure'');\n' ...
        'if export_figures\n' ...
        'for n = 1:numel(figs)\n' ...
        ' if strcmp(figs(n).Type,''figure'')\n' ...
        '  if numel(findall(figs(n),''Type'',''polaraxes'')) > 0, name=''fig3_skyplot''; else, name=''fig2_sat_count''; end\n' ...
        '  savefig(figs(n),fullfile(out_dir,[name ''.fig'']));\n' ...
        '  exportgraphics(figs(n),fullfile(out_dir,[name ''.pdf'']),''ContentType'',''vector'');\n' ...
        ' end\n' ...
        'end\n' ...
        'end\n' ...
        'save(fullfile(out_dir,''satellite_plot_data.mat''),''sat_counts'',''skyplot_data'');\n' ...
        'fprintf(''%%s: %%d observation epochs; %%d satellite tracks\\n'', ''%s'',numel(epochs.time),numel(skyplot_data.tracks));\n' ...
        'drawnow;\n'], site);
    temp_script = fullfile(output_dir, ['run_' site '_satellites.m']);
    fid = fopen(temp_script, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'Cannot write generated entry script');
    fprintf(fid, '%s\n%s\n%s', header, body, source(local_start(1):end));
    fclose(fid);
    fprintf('Rendering %s ...\n', site);
    run(temp_script);
end
fprintf('Satellite figure windows are open; export enabled: %d.\n', export_figures);
end
